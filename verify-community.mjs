import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {readRoute,routeHash,shareURL} from './routes.js';
import {careerQuestion,addCareerQuestions} from './career-practice.js';
import {validateContribution,publicQuestion,validateCommunity,issueURL} from './community-core.js';
import {validateBackup,freshState} from './core.js';
import {COMPANIES,QUESTIONS} from './data.js';
import {COMMUNITY_DATA} from './community-data.js';

assert.equal(readRoute('').view,'bank');
assert.deepEqual(readRoute(routeHash('career','', {query:'星海图 / VLA',salaryEvidence:'experience'})),{view:'career',id:'',params:{query:'星海图 / VLA',salaryEvidence:'experience'}});
assert.equal(readRoute(routeHash('roadmap','预训练')).id,'预训练');
assert.equal(readRoute('#/question/%ZZ').view,'missing');
assert.equal(readRoute('#/unknown').view,'missing');
assert.equal(shareURL('https://example.com/prep/?secret=1#/bank',routeHash('question','vla-01')),'https://example.com/prep/#/question/vla-01');
const career=JSON.parse(await readFile(new URL('./career-data.json',import.meta.url),'utf8'));
const source=career.records.find(r=>r.verification==='original-read'&&r.questions.length>1);
const q=careerQuestion(source,0,COMPANIES);
assert.equal(q.kind,'pending');assert.equal(q.answer,'');assert.equal(q.source.originRecordId,source.id);
assert.equal(q.source.url,source.source.url);
assert.throws(()=>careerQuestion({...source,verification:'lead'},0));
assert.throws(()=>careerQuestion(source,-1));
const added=addCareerQuestions([],source,[0,1],COMPANIES);
const edited={...added.questions[0],answer:'我的答案',kind:'open'};
const again=addCareerQuestions([edited,added.questions[1]],source,[0,1],COMPANIES);
assert.equal(again.added,0);assert.equal(again.questions[0].answer,'我的答案');
const reordered={...source,questions:[...source.questions].reverse()};
assert.equal(careerQuestion(reordered,source.questions.length-1,COMPANIES).id,q.id,'Reordering source topics must not lose personal notes');
const state={...freshState(),customQuestions:again.questions,records:{[q.id]:{draft:'PRIVATE ANSWER',note:'PRIVATE NOTE'}}};
const restored=validateBackup(JSON.parse(JSON.stringify(state)),QUESTIONS.map(q=>q.id));
assert.equal(restored.records[q.id].note,'PRIVATE NOTE');assert.equal(restored.customQuestions[0].source.originRecordId,source.id);
const raw={schemaVersion:1,id:'contrib-fixture',type:'question',createdAt:'2026-11-09T07:00:00Z',target:{type:'general',id:'',title:''},content:{title:'测试题',body:'作者公开分享的问题背景',sourceUrl:'https://example.com/source',company:'示例团队',role:'实习',track:'VLA'},displayName:'贡献者',consent:true,records:state.records,draft:'PRIVATE ANSWER',note:'PRIVATE NOTE'};
const clean=validateContribution(raw);
assert.doesNotMatch(JSON.stringify(clean),/PRIVATE|records|PRIVATE NOTE/);
assert.throws(()=>validateContribution({...raw,consent:false}));
assert.throws(()=>validateContribution({...raw,content:{...raw.content,sourceUrl:'javascript:alert(1)'}}));
assert.equal(issueURL('https://evil.example/a/b',clean),'');
assert.match(issueURL('https://github.com/owner/repo',clean),/^https:\/\/github.com\/owner\/repo\/issues\/new\?/);
const publicQ=publicQuestion(clean);assert.equal(publicQ.kind,'pending');assert.match(publicQ.id,/^community-/);
assert.equal(validateCommunity({schemaVersion:1,questions:[publicQ],reviews:[]}).questions[0].id,publicQ.id);
assert.throws(()=>validateCommunity({schemaVersion:1,questions:[publicQ,publicQ],reviews:[]}));
validateCommunity(COMMUNITY_DATA);
const restoredPublic=validateBackup({...freshState(),records:{[publicQ.id]:{note:'社区题的个人笔记'}}},[...QUESTIONS.map(q=>q.id),publicQ.id]);
assert.equal(restoredPublic.records[publicQ.id].note,'社区题的个人笔记');
console.log('PASS: deep links, stable topic IDs, repeat imports, private record preservation, contribution isolation, reviewed publication and backup compatibility.');
