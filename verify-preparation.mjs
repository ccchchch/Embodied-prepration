import assert from 'node:assert/strict';
import {QUESTIONS} from './data.js';
import {freshState,validateBackup,mergeBackup} from './core.js';
import {defaultGoal,dayKey,planOverview,sessionGroups} from './preparation-core.js';

const now=new Date(2026,10,9,12).getTime(), midnight=new Date(2026,10,9).getTime();
const question=(id,extra={})=>({id,companies:['target'],roles:['research'],track:'VLA',difficulty:'基础',...extra});
const questions=['due','new','today','future','learning','weak'].map(id=>question(id));
questions.push(question('other',{companies:['other']}));
const records={due:{level:'mastered',dueAt:midnight-1,lastAt:midnight-86400000},today:{level:'weak',dueAt:now,lastAt:midnight},future:{level:'mastered',dueAt:now+1,lastAt:midnight-1},learning:{level:'learning',dueAt:now+1,lastAt:midnight-1},weak:{level:'weak',dueAt:now-1,lastAt:midnight-1}};
const goal={company:'target',role:'research',track:'VLA',dailySize:3};
let overview=planOverview(questions,records,goal,now);
assert.equal(overview.doneToday,1,'Local midnight starts a new day');
assert.equal(overview.matched.length,6,'Goal intersections must not include unrelated companies');
assert.deepEqual(overview.queue.map(q=>q.id),['due','weak'],'Overdue questions come first; a weak question graded today must not refill the daily queue');
overview=planOverview(questions,records,{...goal,dailySize:10},now);
assert.deepEqual(overview.queue.map(q=>q.id),['due','weak','new','learning']);
assert.equal(planOverview(questions,records,{...goal,role:'unmatched'},now).queue.length,0,'An empty target must not silently broaden the scope');
assert.equal(dayKey(midnight-1),'2026-11-08');assert.equal(dayKey(midnight),'2026-11-09');
assert.equal(planOverview(questions,{...records,due:{...records.due,lastAt:now},weak:{...records.weak,lastAt:now}},goal,now).queue.length,0,'Three distinct self-assessments satisfy the three-question target');
assert.deepEqual(planOverview(questions,{},defaultGoal(),now).queue.length,5);

const ids=QUESTIONS.map(q=>q.id),[first,second,third]=ids;
const active={id:'session-local',ids:[first,second,third],index:1,grades:{[first]:'weak'},startedAt:now-1000,updatedAt:now,returnView:'plan',returnId:''};
const state={...freshState(),preparation:{goal,active,history:[]},records:{[first]:{note:'KEEP PRIVATE NOTE',draft:'KEEP PRIVATE ANSWER'}}};
const restored=validateBackup(JSON.parse(JSON.stringify(state)),ids);
assert.deepEqual(restored.preparation,state.preparation);
assert.equal(restored.records[first].note,'KEEP PRIVATE NOTE');
const legacy={...state};delete legacy.preparation;
assert.deepEqual(validateBackup(legacy,ids).preparation,freshState().preparation,'Existing backups without planning data remain valid');
assert.equal(validateBackup(legacy,ids).records[first].draft,'KEEP PRIVATE ANSWER');
const cleaned=validateBackup({...state,preparation:{...state.preparation,secret:'DROP',active:{...active,token:'DROP'}}},ids);
assert.doesNotMatch(JSON.stringify(cleaned.preparation),/DROP|secret|token/,'Planning uses an explicit allowlist too');
const removed=validateBackup({...state,preparation:{...state.preparation,active:{...active,ids:[first,'removed',third],index:1}}},ids);
assert.deepEqual(removed.preparation.active.ids,[first,third]);assert.equal(removed.preparation.active.index,0);
assert.throws(()=>validateBackup({...state,preparation:{...state.preparation,goal:{...goal,dailySize:999}}},ids));
assert.throws(()=>validateBackup({...state,preparation:{...state.preparation,active:{...active,grades:{[first]:'automatic-pass'}}}},ids));
assert.throws(()=>validateBackup({...state,preparation:{...state.preparation,active:{...active,index:99}}},ids));
const incoming={...freshState(),preparation:{goal:{...goal,dailySize:10},active:{...active,id:'session-incoming',index:2},history:[]}};
const merged=mergeBackup(restored,validateBackup(incoming,ids));
assert.equal(merged.preparation.goal.dailySize,3);
assert.equal(merged.preparation.active.id,'session-local');
assert.equal(merged.preparation.history[0].id,'session-incoming','Imported progress stays recoverable without replacing local progress');
assert.equal(mergeBackup(merged,incoming).preparation.history.length,1,'Repeated imports cannot duplicate a session');
assert.deepEqual(validateBackup(JSON.parse(JSON.stringify(merged)),ids).preparation,merged.preparation);
assert.equal(mergeBackup(freshState(),incoming).preparation.active.id,'session-incoming','A fresh browser restores the imported queue');
const completed={...freshState(),preparation:{goal:null,active:null,history:[{...incoming.preparation.active,finishedAt:now,reason:'completed'}]}};
assert.equal(mergeBackup(completed,incoming).preparation.active,null,'Importing an old backup must not reopen a locally completed session');
assert.deepEqual(sessionGroups(active),{weak:[first],learning:[],mastered:[],skipped:[second,third]});
console.log('PASS: daily planning priorities and limits, local-day boundaries, goal scope, no repeat counting, old/new backups, queue restoration, safe merge and skipped-vs-graded reports.');
